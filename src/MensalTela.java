    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String descricao = txtDescricao.getText().trim();
String sigla = txtSigla.getText().trim();
String status = txtStatus.getText().trim();

if (descricao.isEmpty() || sigla.isEmpty() || status.isEmpty()) {
    JOptionPane.showMessageDialog(this,
        "Preencha todos os campos obrigatórios.");
    return;
}

try {
    Genero genero = new Genero();

    genero.setDescricao(descricao);
    genero.setSigla(sigla);
    genero.setStat(status);

    GeneroDao generoDao = new GeneroDao();
    generoDao.inserir(genero);

    JOptionPane.showMessageDialog(this,
        "Gênero cadastrado com sucesso!");

    txtCodigo.setText("");
    txtDescricao.setText("");
    txtSigla.setText("");
    txtStatus.setText("");

} catch (Exception ex) {
    JOptionPane.showMessageDialog(this,
        "Erro ao cadastrar gênero: " + ex.getMessage(),
        "Erro",
        JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if (txtCodigo.getText().trim().isEmpty()) {
    JOptionPane.showMessageDialog(this,
        "Informe o código do gênero que deseja alterar.");
    return;
}

String descricao = txtDescricao.getText().trim();
String sigla = txtSigla.getText().trim();
String status = txtStatus.getText().trim();

if (descricao.isEmpty() || sigla.isEmpty() || status.isEmpty()) {
    JOptionPane.showMessageDialog(this,
        "Preencha todos os campos obrigatórios.");
    return;
}

try {
    Genero genero = new Genero();

    genero.setId(Integer.parseInt(txtCodigo.getText().trim()));
    genero.setDescricao(descricao);
    genero.setSigla(sigla);
    genero.setStat(status);

    GeneroDao generoDao = new GeneroDao();
    generoDao.alterar(genero);

    JOptionPane.showMessageDialog(this,
        "Operação de alteração executada.");

} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(this,
        "O código deve ser um número inteiro válido.");
} catch (Exception ex) {
    JOptionPane.showMessageDialog(this,
        "Erro ao alterar gênero: " + ex.getMessage(),
        "Erro",
        JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_jButton2ActionPerformed

    private void tbGenerosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbGenerosMouseClicked
        
int linha = tbGeneros.getSelectedRow();

if (linha == -1) {
    return;
}

txtCodigo.setText(tbGeneros.getValueAt(linha, 0).toString());
txtDescricao.setText(tbGeneros.getValueAt(linha, 1).toString());
txtSigla.setText(tbGeneros.getValueAt(linha, 2).toString());
txtStatus.setText(tbGeneros.getValueAt(linha, 3).toString());

    }//GEN-LAST:event_tbGenerosMouseClicked

