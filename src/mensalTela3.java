    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        
try {
    String nome = txtNome.getText().trim();
    String descricao = txtDescricao.getText().trim();
    String valorPreco = txtPreco.getText().trim().replace(",", ".");

    if (nome.isEmpty() || valorPreco.isEmpty()
            || cbCategoria.getSelectedItem() == null) {

        JOptionPane.showMessageDialog(this,
                "Preencha o nome, o preço e a categoria.");
        return;
    }

    BigDecimal preco = new BigDecimal(valorPreco);

    if (preco.compareTo(BigDecimal.ZERO) < 0
            || preco.scale() > 2
            || preco.compareTo(new BigDecimal("99999999.99")) > 0) {

        JOptionPane.showMessageDialog(this,
                "Informe um preço válido, com até duas casas decimais.");
        return;
    }

    Produto produto = new Produto();

    produto.setNome(nome);
    produto.setDescricao(descricao);
    produto.setPreco(preco);
    produto.setCategoria(cbCategoria.getSelectedItem().toString());

    ProdutoDao produtoDao = new ProdutoDao();
    produtoDao.inserir(produto);

    JOptionPane.showMessageDialog(this,
            "Produto cadastrado com sucesso!");
    
    atualizarTabela();

    txtCodigo.setText("");
    txtNome.setText("");
    txtDescricao.setText("");
    txtPreco.setText("");
    cbCategoria.setSelectedIndex(0);

    txtNome.requestFocus();

} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(this,
            "Preço inválido. Exemplo: 199,90",
            "Erro de validação",
            JOptionPane.ERROR_MESSAGE);

} catch (Exception ex) {
    JOptionPane.showMessageDialog(this,
            "Erro ao cadastrar produto: " + ex.getMessage(),
            "Erro",
            JOptionPane.ERROR_MESSAGE);
}

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        
try {
    String codigo = txtCodigo.getText().trim();
    String nome = txtNome.getText().trim();
    String descricao = txtDescricao.getText().trim();
    String valorPreco = txtPreco.getText().trim().replace(",", ".");

    if (codigo.isEmpty() || nome.isEmpty() || valorPreco.isEmpty()
            || cbCategoria.getSelectedItem() == null) {

        JOptionPane.showMessageDialog(this,
                "Informe o código, nome, preço e categoria.");
        return;
    }

    int id = Integer.parseInt(codigo);
    BigDecimal preco = new BigDecimal(valorPreco);

    if (id <= 0 || preco.compareTo(BigDecimal.ZERO) < 0
            || preco.scale() > 2
            || preco.compareTo(new BigDecimal("99999999.99")) > 0) {

        JOptionPane.showMessageDialog(this,
                "Código ou preço inválido.");
        return;
    }

    Produto produto = new Produto();

    produto.setId(id);
    produto.setNome(nome);
    produto.setDescricao(descricao);
    produto.setPreco(preco);
    produto.setCategoria(cbCategoria.getSelectedItem().toString());

    ProdutoDao produtoDao = new ProdutoDao();
    produtoDao.alterar(produto);

    JOptionPane.showMessageDialog(this,
            "Produto alterado com sucesso!");
    
    atualizarTabela();

    txtCodigo.setText("");
    txtNome.setText("");
    txtDescricao.setText("");
    txtPreco.setText("");
    cbCategoria.setSelectedIndex(0);

    txtNome.requestFocus();

} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(this,
            "Código ou preço inválido.",
            "Erro de validação",
            JOptionPane.ERROR_MESSAGE);

} catch (Exception ex) {
    JOptionPane.showMessageDialog(this,
            "Erro ao alterar produto: " + ex.getMessage(),
            "Erro",
            JOptionPane.ERROR_MESSAGE);
}

    }//GEN-LAST:event_jButton2ActionPerformed

    private void tbProdutosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbProdutosMouseClicked
        
int linha = tbProdutos.getSelectedRow();

if (linha == -1) {
    return;
}

try {
    int id = Integer.parseInt(
            tbProdutos.getValueAt(linha, 0).toString());

    ProdutoDao produtoDao = new ProdutoDao();
    ArrayList<Produto> produtos = produtoDao.consultar();

    for (Produto produto : produtos) {

        if (produto.getId() == id) {

            txtCodigo.setText(String.valueOf(produto.getId()));
            txtNome.setText(produto.getNome());
            txtDescricao.setText(produto.getDescricao());
            txtPreco.setText(
                    produto.getPreco().toString().replace(".", ","));
            cbCategoria.setSelectedItem(produto.getCategoria());

            break;
        }
    }

} catch (Exception ex) {
    JOptionPane.showMessageDialog(this,
            "Erro ao selecionar produto: " + ex.getMessage(),
            "Erro",
            JOptionPane.ERROR_MESSAGE);
}

    }//GEN-LAST:event_tbProdutosMouseClicked

