    private void tbClientesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tbClientesMouseClicked
        
int linha = tbClientes.getSelectedRow();

if (linha == -1) {
    return;
}

try {
    int id = Integer.parseInt(
            tbClientes.getValueAt(linha, 0).toString());

    ClienteDao clienteDao = new ClienteDao();
    ArrayList<Cliente> lista = clienteDao.consultar();

    for (Cliente cliente : lista) {
        if (cliente.getId() == id) {

            idClienteSelecionado = cliente.getId();

            txtNome.setText(cliente.getNome());
            txtCpf.setText(cliente.getCpf());

            txtDataNascimento.setText(
                    cliente.getDataNascimento().format(
                            DateTimeFormatter.ofPattern("dd/MM/yyyy")));

            txtTelefone.setText(cliente.getTelefone());

            cbGenero.setSelectedItem(
                    cliente.getGeneroId() + " - " +
                    buscarDescricaoGenero(cliente.getGeneroId()));

            txtCep.setText(cliente.getCep());
            txtLogradouro.setText(cliente.getLogradouro());
            txtBairro.setText(cliente.getBairro());
            txtCidade.setText(cliente.getCidade());
            cbUf.setSelectedItem(cliente.getUf());
            txtNumero.setText(cliente.getNumero());
            txtComplemento.setText(cliente.getComplemento());

            break;
        }
    }

} catch (Exception ex) {
    JOptionPane.showMessageDialog(this,
            "Erro ao selecionar cliente: " + ex.getMessage(),
            "Erro",
            JOptionPane.ERROR_MESSAGE);
}

    }//GEN-LAST:event_tbClientesMouseClicked

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        
if (idClienteSelecionado == 0) {
    JOptionPane.showMessageDialog(this,
            "Selecione um cliente na tabela antes de alterar.");
    return;
}

try {
    String nome = txtNome.getText().trim();
    String cpf = txtCpf.getText().trim();
    String data = txtDataNascimento.getText().trim();
    String telefone = txtTelefone.getText().trim();
    String cep = txtCep.getText().trim();
    String logradouro = txtLogradouro.getText().trim();
    String bairro = txtBairro.getText().trim();
    String cidade = txtCidade.getText().trim();
    String numero = txtNumero.getText().trim();

    if (nome.isEmpty() || cpf.isEmpty() || telefone.isEmpty()
            || cep.isEmpty() || logradouro.isEmpty()
            || bairro.isEmpty() || cidade.isEmpty() || numero.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Preencha todos os campos obrigatórios.");
        return;
    }

    java.time.format.DateTimeFormatter formato =
            java.time.format.DateTimeFormatter.ofPattern("dd/MM/uuuu")
                    .withResolverStyle(java.time.format.ResolverStyle.STRICT);

    java.time.LocalDate nascimento =
            java.time.LocalDate.parse(data, formato);

    if (cbGenero.getSelectedItem() == null || cbUf.getSelectedItem() == null) {
        JOptionPane.showMessageDialog(this,
                "Selecione o gênero e a UF.");
        return;
    }

    String generoSelecionado = cbGenero.getSelectedItem().toString();
    int generoId = Integer.parseInt(generoSelecionado.split(" - ", 2)[0]);

    Cliente cliente = new Cliente();

    cliente.setId(idClienteSelecionado);
    cliente.setNome(nome);
    cliente.setCpf(cpf);
    cliente.setDataNascimento(nascimento);
    cliente.setTelefone(telefone);
    cliente.setGeneroId(generoId);
    cliente.setCep(cep);
    cliente.setLogradouro(logradouro);
    cliente.setBairro(bairro);
    cliente.setCidade(cidade);
    cliente.setUf(cbUf.getSelectedItem().toString());
    cliente.setNumero(numero);
    cliente.setComplemento(txtComplemento.getText().trim());

    ClienteDao clienteDao = new ClienteDao();
    clienteDao.alterar(cliente);

    JOptionPane.showMessageDialog(this,
            "Cliente alterado com sucesso!");

    limparCampos();
    atualizarTabela();

} catch (java.time.format.DateTimeParseException ex) {
    JOptionPane.showMessageDialog(this,
            "Data de nascimento inválida. Utilize dd/MM/aaaa.",
            "Erro de validação",
            JOptionPane.ERROR_MESSAGE);

} catch (Exception ex) {
    JOptionPane.showMessageDialog(this,
            "Erro ao alterar cliente: " + ex.getMessage(),
            "Erro",
            JOptionPane.ERROR_MESSAGE);
}

    }//GEN-LAST:event_jButton2ActionPerformed

