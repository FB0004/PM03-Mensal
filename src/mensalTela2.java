private void atualizarTabela() {
    try {
        ClienteDao clienteDao = new ClienteDao();
        ArrayList<Cliente> clientes = clienteDao.consultar();

        DefaultTableModel modelo =
                (DefaultTableModel) tbClientes.getModel();

        modelo.setRowCount(0);

        for (Cliente cliente : clientes) {
            String descricaoGenero = "";

            for (int i = 0; i < cbGenero.getItemCount(); i++) {
                String item = cbGenero.getItemAt(i);

                if (item.startsWith(cliente.getGeneroId() + " - ")) {
                    descricaoGenero = item.substring(item.indexOf(" - ") + 3);
                    break;
                }
            }

            modelo.addRow(new Object[]{
                cliente.getId(),
                cliente.getNome(),
                cliente.getCpf(),
                cliente.getTelefone(),
                descricaoGenero
            });
        }

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this,
                "Erro ao carregar clientes: " + ex.getMessage(),
                "Erro",
                JOptionPane.ERROR_MESSAGE);
    }
}


private String buscarDescricaoGenero(int generoId) {

    for (int i = 0; i < cbGenero.getItemCount(); i++) {

        String item = cbGenero.getItemAt(i);

        if (item.startsWith(generoId + " - ")) {
            return item.substring(item.indexOf(" - ") + 3);
        }
    }

    return "";
}



