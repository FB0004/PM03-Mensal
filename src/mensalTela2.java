private void carregarGeneros() {
    try {
        GeneroDao generoDao = new GeneroDao();
        ArrayList<Genero> lista = generoDao.consultar();

        cbGenero.removeAllItems();

        for (Genero genero : lista) {
            cbGenero.addItem(genero.getId() + " - " + genero.getDescricao());
        }

    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this,
            "Erro ao carregar gêneros: " + ex.getMessage(),
            "Erro",
            JOptionPane.ERROR_MESSAGE);
    }
}

